import { chromium, devices } from 'playwright';
const BASE = process.env.BASE_URL ?? 'http://localhost:8080', OUT = process.argv[2] ?? 'e2e/shots';
const api = async (m, p, b, t) => { const r = await fetch(BASE+p,{method:m,headers:{'content-type':'application/json',...(t?{authorization:'Bearer '+t}:{})},body:b?JSON.stringify(b):undefined}); return r.json(); };
const login = async (ph) => { const c = await api('POST','/api/auth/code',{phone:ph}); return (await api('POST','/api/auth/verify',{phone:ph,code:c.devCode})).token; };
const adm = await login('+79990000001'), k = await login('+79991112233');
for (const t of [k,adm]) for (const aud of ['client','privacy']) { const o = await api('GET','/api/offers/current/'+aud); if (o) await api('POST','/api/offers/'+o.id+'/accept',{},t); }
const b = await chromium.launch(); const errs=[];
const C = async (l) => { await l.first().evaluate(e=>e.scrollIntoView({block:'center'})); await l.first().click(); };
const page = async (tok, w) => { const ctx = await b.newContext({...devices['iPhone 13']}); await ctx.addInitScript((t)=>{try{localStorage.setItem('traksos.token',t)}catch{}}, tok); const p = await ctx.newPage(); p.on('pageerror',e=>errs.push(w+': '+e.message)); p.on('console',c=>c.type()==='error'&&!c.text().includes('TUNNEL')&&errs.push(w+': '+c.text())); return p; };
const shot = (p,n) => p.screenshot({path:`${OUT}/${n}.png`,fullPage:true});
const kp = await page(k,'client'); await kp.goto(BASE+'/#/shop'); await kp.waitForTimeout(1000); await shot(kp,'s1-closed');
const ap = await page(adm,'admin'); await ap.goto(BASE+'/#/admin'); await ap.waitForTimeout(800);
await C(ap.getByRole('button',{name:'Магазин',exact:true})); await ap.waitForTimeout(600);
await C(ap.getByRole('tab',{name:'Товары'})); await ap.waitForTimeout(400);
await C(ap.getByRole('button',{name:'+ Добавить товар'}));
await ap.getByPlaceholder('Розетка 15-контактная').fill('Тревожный чемоданчик');
await ap.getByPlaceholder('24 В · ISO 12098').fill('Розетка, перекидка, адаптер, предохранители');
await C(ap.getByRole('button',{name:'Наборы',exact:true}));
await ap.locator('input[inputmode=decimal], input[inputmode=numeric]').first().fill('4500');
await shot(ap,'a1-form');
await C(ap.getByRole('button',{name:'Сохранить',exact:true})); await ap.waitForTimeout(800);
await C(ap.getByRole('button',{name:'+ Добавить товар'}));
await ap.getByPlaceholder('Розетка 15-контактная').fill('Розетка 15-контактная');
await ap.getByPlaceholder('24 В · ISO 12098').fill('24 В · ISO 12098');
await C(ap.getByRole('button',{name:'Розетки',exact:true}));
const nums = ap.locator('input[inputmode=decimal], input[inputmode=numeric]'); await nums.nth(0).fill('1200'); await nums.nth(1).fill('3');
await C(ap.getByRole('button',{name:'Сохранить',exact:true})); await ap.waitForTimeout(800);
await shot(ap,'a2-products');
await C(ap.getByRole('button',{name:'Открыть магазин'})); await ap.waitForTimeout(800);
await kp.reload(); await kp.waitForTimeout(1200); await shot(kp,'s2-open');
await C(kp.getByRole('button',{name:'В корзину'})); await C(kp.getByRole('button',{name:'Добавить: Розетка 15-контактная'})); await kp.waitForTimeout(300);
await C(kp.getByRole('button',{name:/^Корзина ·/})); await kp.waitForTimeout(800);
await C(kp.getByRole('button',{name:/Самовывоз/})); await shot(kp,'s3-cart');
await C(kp.getByRole('button',{name:'Оформить заказ'})); await kp.waitForTimeout(1200); await shot(kp,'s4-done');
await C(ap.getByRole('tab',{name:'Заказы'})); await ap.waitForTimeout(800);
await ap.getByPlaceholder('Сообщение клиенту · по желанию').fill('Заберите завтра после 10:00');
await C(ap.getByRole('button',{name:'Подтвердить'})); await ap.waitForTimeout(800); await shot(ap,'a3-orders');
await kp.reload(); await kp.waitForTimeout(1000);
const st = await api('GET','/api/shop/orders',undefined,k); console.log('status', st[0].status, st[0].adminNote);
await b.close();
if (errs.length) { console.error('Ошибки в консоли:', errs); process.exit(1); }
console.log('Магазин: пройдено');
