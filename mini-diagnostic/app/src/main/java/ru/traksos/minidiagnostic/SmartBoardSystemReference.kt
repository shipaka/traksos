    fun find(d:Boolean,component:String,type:String):DisplayLookup? {
        val c=(if(d)oldD else oldE)[component]
        // Original system manual prints two 05 rows for D, and its E table
        // disagrees with the worked example. Do not resolve 05 as a specific fault.
        val t=when(type) {
            "05" -> "Противоречие в руководстве: требуется уточнение типа неисправности"
            "06" -> if(d) null else "Повышенный ток или КЗ на массу"
            "09" -> if(d) "Нарушение приёма данных" else "Нарушение сигнала"
            "10" -> if(d) null else "Скачок значения"
            else -> types[type]
        }
        if(c==null && t==null)return null
        return DisplayLookup(c,t,SYSTEM_SOURCE,false)
    }
    val systemComponentCount get()=oldD.size+oldE.size
    val driverExtraCount get()=driverD.size+driverE.size
