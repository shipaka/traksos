    fun detailedLookup(code:String):DisplayLookup? {
        val r=lookup(EcuFamily.VIE_TEBS,code) ?: return null
        val n=r.section.substringAfter("A1.").toInt()
        val note=if(n<=20) sensorAdvice.getValue(code.substringAfter('/').toInt()) else advice.getValue(code)
        return DisplayLookup(r.component,r.condition+". "+note,PDF+"#page="+pages[n-1]+" · "+DOCUMENT+" · "+r.section,true)
    }
    private val index=(sensorEntries+other).associateBy { it.code }
    val count:Int get()=index.size
    fun lookup(family:EcuFamily,displayCode:String):VieDisplayDtc? =
        if(family==EcuFamily.VIE_TEBS) index[displayCode] else null
    fun entries(family:EcuFamily):List<VieDisplayDtc> =
        if(family==EcuFamily.VIE_TEBS) index.values.toList() else emptyList()
