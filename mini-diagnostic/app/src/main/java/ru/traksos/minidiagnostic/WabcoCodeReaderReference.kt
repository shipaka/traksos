    fun lookup(edition:DisplayReferenceEdition,code:String):DisplayLookup? {
        if(!Regex("[0-9]{1,3}/[0-9]{1,2}").matches(code)) return null
        val (spn,fmi)=code.split("/").map { it.toInt() }
        val component=when(edition) {
            DisplayReferenceEdition.WABCO_VCS2_READER -> vcs[spn]
            DisplayReferenceEdition.WABCO_D_READER -> d[spn]
            DisplayReferenceEdition.WABCO_E_READER -> e[spn]
            else -> return null
        } ?: return null
        val condition=(if(edition==DisplayReferenceEdition.WABCO_VCS2_READER) vcsTypes else tebsTypes).getOrNull(fmi) ?: return null
        val componentPage=when(edition) {
            DisplayReferenceEdition.WABCO_VCS2_READER -> if(spn<=9) 19 else 20
            DisplayReferenceEdition.WABCO_D_READER -> if(spn<=4) 20 else 21
            else -> ePages.entries.first { spn in it.value }.key
        }
        val typePage=when(edition) {
            DisplayReferenceEdition.WABCO_VCS2_READER -> 20
            DisplayReferenceEdition.WABCO_D_READER -> if(fmi<=11) 21 else 22
            else -> 25
        }
        return DisplayLookup(component,condition,listOf(componentPage,typePage).distinct().joinToString("\n") { SOURCE+"#page="+it },false)
    }
