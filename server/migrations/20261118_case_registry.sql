-- Read-only case index. The public multi-case number is assigned once and never reused.
-- Existing order IDs and order numbers are not changed.
create table if not exists case_registry (
  root_order_id uuid primary key references orders(id),
  multi_number bigint generated by default as identity unique not null,
  created_at timestamptz not null default now()
);
create index if not exists case_registry_number_idx on case_registry(multi_number);
-- Historical root cases get their stable registry number without modifying their orders.
insert into case_registry(root_order_id)
  select o.id from orders o where o.case_root_id is null
  on conflict(root_order_id) do nothing;
insert into case_registry(root_order_id)
  select distinct o.case_root_id from orders o
  join orders root on root.id=o.case_root_id
  where o.case_root_id is not null
  on conflict(root_order_id) do nothing;
-- Keep the registry consistent for new orders and new linked stages.
create or replace function traksos_register_case_on_order()
returns trigger language plpgsql as $$
begin
  insert into case_registry(root_order_id)
    values (coalesce(new.case_root_id, new.id))
    on conflict(root_order_id) do nothing;
  return new;
end $$;
drop trigger if exists traksos_case_registry_order_insert on orders;
create trigger traksos_case_registry_order_insert
  after insert on orders
  for each row execute function traksos_register_case_on_order();
