-- A multi-case gets its own sequence only when a second linked stage exists.
-- Never rewrite or reuse ordinary performer order numbers.
create table if not exists case_registry (
  root_order_id uuid primary key references orders(id),
  multi_number bigint generated by default as identity unique not null,
  created_at timestamptz not null default now()
);
create index if not exists case_registry_number_idx on case_registry(multi_number);

-- Backfill real linked cases only: prior SOS continuations and workshop stages.
insert into case_registry(root_order_id)
  select distinct root_id from (
    select o.case_root_id as root_id from orders o where o.case_root_id is not null
    union
    select b.case_root_id as root_id from service_bookings b where b.case_root_id is not null
  ) x
  join orders root on root.id=x.root_id
  on conflict(root_order_id) do nothing;

create or replace function traksos_register_case_on_order()
returns trigger language plpgsql as $$
begin
  if new.case_root_id is not null then
    insert into case_registry(root_order_id)
      values (new.case_root_id)
      on conflict(root_order_id) do nothing;
  end if;
  return new;
end $$;
drop trigger if exists traksos_case_registry_order_insert on orders;
create trigger traksos_case_registry_order_insert
  after insert on orders
  for each row execute function traksos_register_case_on_order();

create or replace function traksos_register_case_on_booking()
returns trigger language plpgsql as $$
begin
  if new.case_root_id is not null then
    insert into case_registry(root_order_id)
      values (new.case_root_id)
      on conflict(root_order_id) do nothing;
  end if;
  return new;
end $$;
drop trigger if exists traksos_case_registry_booking_insert on service_bookings;
create trigger traksos_case_registry_booking_insert
  after insert on service_bookings
  for each row execute function traksos_register_case_on_booking();
