-- Assign a separate M sequence only after the case acquires a linked second stage.
-- Preserve unique original order numbers and immutable stage ordinals.
create table if not exists case_registry (
  root_order_id uuid primary key references orders(id),
  multi_number bigint generated by default as identity unique not null,
  created_at timestamptz not null default now()
);
create index if not exists case_registry_number_idx on case_registry(multi_number);

create table if not exists case_stage_index (
  root_order_id uuid not null references case_registry(root_order_id),
  source_kind text not null check (source_kind in ('order','booking')),
  source_id uuid not null,
  ordinal integer not null check (ordinal>0),
  created_at timestamptz not null default now(),
  primary key(root_order_id,source_kind,source_id),
  unique(root_order_id,ordinal)
);

insert into case_registry(root_order_id)
select distinct root_id from (
  select o.case_root_id as root_id from orders o where o.case_root_id is not null
  union
  select b.case_root_id as root_id from service_bookings b where b.case_root_id is not null
) x join orders root on root.id=x.root_id
on conflict(root_order_id) do nothing;

-- Stable one-time backfill for existing cases, combining orders and service bookings by event time.
insert into case_stage_index(root_order_id,source_kind,source_id,ordinal)
select root_id,source_kind,source_id,
       row_number() over(partition by root_id order by at,source_kind,source_id)::int
from (
  select cr.root_order_id as root_id,'order'::text as source_kind,
         o.id as source_id,o.created_at as at
  from case_registry cr join orders o on o.id=cr.root_order_id
  union all
  select cr.root_order_id as root_id,'order'::text as source_kind,
         o.id as source_id,o.created_at as at
  from orders o join case_registry cr on cr.root_order_id=o.case_root_id
  union all
  select cr.root_order_id as root_id,'booking'::text as source_kind,
         b.id as source_id,b.created_at as at
  from service_bookings b join case_registry cr on cr.root_order_id=b.case_root_id
) events
on conflict do nothing;

create or replace function traksos_register_case_on_order()
returns trigger language plpgsql as $$
declare next_ordinal int;
begin
  if new.case_root_id is null then return new; end if;
  perform pg_advisory_xact_lock(hashtext('traksos-case:'||new.case_root_id::text));
  insert into case_registry(root_order_id) values (new.case_root_id)
    on conflict(root_order_id) do nothing;
  insert into case_stage_index(root_order_id,source_kind,source_id,ordinal)
    values (new.case_root_id,'order',new.case_root_id,1)
    on conflict(root_order_id,source_kind,source_id) do nothing;
  select coalesce(max(ordinal),0)+1 into next_ordinal
    from case_stage_index where root_order_id=new.case_root_id;
  insert into case_stage_index(root_order_id,source_kind,source_id,ordinal)
    values (new.case_root_id,'order',new.id,next_ordinal)
    on conflict(root_order_id,source_kind,source_id) do nothing;
  return new;
end $$;
drop trigger if exists traksos_case_registry_order_insert on orders;
create trigger traksos_case_registry_order_insert after insert on orders
  for each row execute function traksos_register_case_on_order();

