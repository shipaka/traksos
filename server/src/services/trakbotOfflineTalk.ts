export function isOfflineCasual(text: string): boolean {
  return !TECHNICAL.test(text) && !SENSITIVE.test(text);
}

function nice(text: string): string {
  return text.replace(/\s+/g, ' ').trim().toLowerCase();
}

export function offlineSmallTalk(
  message: string,
  previousUserMessages: string[] = [],
): string | null {
  const input = nice(message);
  if (!input || input.length > 220 || !isOfflineCasual(input)) return null;
  const previous = previousUserMessages.slice(0, 12).map(nice);

  const storyContinuation = CONTINUE.test(input) && previous.some((p) => STORY.test(p));
  if (STORY.test(input) || storyContinuation) {
    if (storyContinuation) {
      const anchor = previous.findIndex((p) => STORY.test(p));
      if (anchor < 0 || previous.slice(0, anchor).some((p) => !CONTINUE.test(p))) return null;
      const idx = Math.max(0, previous.filter((p) => STORY.test(p)).length - 1) % stories.length;
      const story = stories[idx];
      return anchor < story.parts.length - 1 ? story.parts[anchor + 1] : 'Эта история закончилась. Хочешь новую? Напиши «расскажи историю».';
    }
    const idx = previous.filter((p) => STORY.test(p)).length % stories.length;
    const story = stories[idx];
    return story.title + '. ' + story.parts[0];
  }

  const last = previous[0] ?? '';
  const jokeContinuation = CONTINUE.test(input) && (JOKE.test(last) ||
    (CONTINUE.test(last) && previous.some((p) => JOKE.test(p)) && !previous.some((p) => STORY.test(p))));
  if (JOKE.test(input) || jokeContinuation) {
    const idx = previous.filter((p) => JOKE.test(p) || CONTINUE.test(p)).length % jokes.length;
    return jokes[idx] + ' Ещё одну?';
  }

  if (/^(?:привет|приветик|здравствуй|салют|здорово|хай|добрый день|добрый вечер)[!?.\s]*$/i.test(input))
    return 'Здорово! Рад, что заглянул. Как дела? Могу и поболтать, и шутку выдать, и короткую историю рассказать.';
  if (/как дела|как жизнь|как ты|как настроение|что нового у тебя/i.test(input) && input.length < 85)
    return 'Всё ровно, на связи. Я автоматический помощник, но настроение в разговоре поддержать могу. А твой день как проходит?';
  if (/^(?:спасибо|спасибо большое|спс|благодарю|пасиб)[!?.\s]*$/i.test(input))
    return 'Да не за что! Обращайся. Если хочешь — могу рассказать что-нибудь весёлое.';
  if (/^(?:устал|устал сегодня|устал капец|тяж[её]лый день)[!?.\s]*$/i.test(input)) {
    return 'Понимаю, день мог вымотать. Хочешь отвлечься на короткую историю или просто поговорить?';
  }
  if (/^(?:скучно|мне скучно|скука)[!?.\s]*$/i.test(input))
    return 'Так, объявляю маленький перерыв от скуки. Шутку, историю или просто поболтаем?';
  if (/^(?:нормально|норм|всё хорошо|все хорошо|отлично|классно|замечательно|неплохо)[!?.\s]*$/i.test(input) &&
      /как дела|как жизнь|как настроение|поболта|как проходит|как день/i.test(last))
    return 'Вот и хорошо. Что приятного сегодня случилось? Или хочешь просто пару минут отвлечься?';
  if (/^(?:а у тебя|а ты|а у тебя как)[!?.\s]*$/i.test(input) &&
      /как дела|как жизнь|как настроение|нормально|отлично|поболта/i.test(last))
    return 'У меня всё спокойно: смена бесконечная, зато перерыв на чай виртуальный. А тебе что сегодня подняло настроение?';
  if (/^(?:поговорим|поболтаем|хочу поболтать|давай пообщаемся|просто поговорить)[!?.\s]*$/i.test(input))
    return 'Погнали. Что выбираешь: дорога, смешные случаи или вообще любая тема? Не буду всё сводить к диагностике.';
  if (/интересн(ый|ые) факт|удиви меня|что-нибудь интересное/i.test(input))
    return 'Небольшое наблюдение из жизни гаража: иногда самая приятная находка — это инструмент, который уже лежит у тебя в руке. Хочешь шутку или историю?';
  return null;
}
