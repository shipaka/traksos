import {test,before,after} from 'node:test';
import assert from 'node:assert/strict';
import {setup,ok,type T} from './helpers.ts';
import {PlannedOrderIntentService} from '../src/services/plannedOrderIntent.ts';
import {ReservationAgreement} from '../src/services/reservationAgreement.ts';
import {plannedEstimate} from '../src/domain/plannedEstimate.ts';
import {defaultSettings} from '../src/domain/defaults.ts';
import {estimate} from '../src/domain/pricing.ts';

const site={regionId:'spb',zoneId:'spb',address:'Санкт-Петербург, тестовый адрес',tier:'eco'} as const;
const day={startsAt:'2026-12-03T08:00:00Z',endsAt:'2026-12-03T10:00:00Z'};
const night={startsAt:'2026-12-03T22:00:00Z',endsAt:'2026-12-04T00:00:00Z'};
const code=(c:string)=>(e:any)=>e?.code===c;
test('preliminary estimate uses existing scheduled-time tariff and capped customer fee',()=>{
  const a=plannedEstimate(defaultSettings,'electric',new Date(day.startsAt),site,null);
  const b=plannedEstimate(defaultSettings,'electric',new Date(night.startsAt),site,null);
  assert.equal(a.tariff.callOut,estimate(defaultSettings.pricing,{service:'electric',tier:'eco',zoneId:'spb',night:false,group:false}).callOut);
  assert.equal(b.tariff.night,true);
  assert.ok(b.tariff.callOut>a.tariff.callOut);
  assert.equal(a.callOutWithFee,a.tariff.callOut+a.clientFee);
  assert.equal(a.financialConsent,false);
  assert.equal(a.includesWork,false);
  const expensive=structuredClone(defaultSettings);
  expensive.pricing.tiers.eco.callOut=20_000_000;
  assert.equal(plannedEstimate(expensive,'electric',new Date(day.startsAt),site,5).clientFee,500_000);
  assert.throws(()=>plannedEstimate(defaultSettings,'electric',new Date(day.startsAt),{...site,address:'Москва, Тверская'},null),code('address_region_mismatch'));
});
let t:T,owner:{id:string;token:string},master:typeof owner,other:typeof owner,agreement:ReservationAgreement,selected:string;
before(async()=>{
  t=await setup();
  owner=await t.login('+79997811201');master=await t.login('+79997811202','master');other=await t.login('+79997811203');
  ok(await t.api('PUT','/api/performer/profile',{kind:'master',name:'Мастер',specialties:['electric']},master.token));
  const vehicle=ok(await t.api('POST','/api/vehicles',{brand:'DAF',model:'XF',plate:'А123АА178'},owner.token)).id;
  const intents=new PlannedOrderIntentService(t.db,t.clock.now);
  const i=await intents.request(owner,{vehicleId:vehicle,service:'electric',requestKey:'estimate_intent_001',...day});
  await intents.decide(owner,i.id,1,true);
  agreement=new ReservationAgreement(t.db,t.app.orders,t.clock.now);
  const r=await agreement.requestForIntent(owner,i.id,master.id,'estimate_reserve_001');
  await agreement.select(master,r.id,1,day);selected=r.id;
});
after(()=>t?.close());
test('owner can acknowledge only exact current estimate, with no order or payment',async()=>{
  const quote=await agreement.quotePlanned(owner,selected,2,site,t.app.settings);
  await assert.rejects(agreement.acknowledgePlannedEstimate(other,selected,2,quote.id,t.app.settings),code('forbidden'));
  const changed=structuredClone(await t.app.settings.all());
  changed.fees.clientFeePct=7;
  await assert.rejects(agreement.acknowledgePlannedEstimate(owner,selected,2,quote.id,{all:async()=>changed}),code('planned_estimate_changed'));
  const acknowledged=await agreement.acknowledgePlannedEstimate(owner,selected,2,quote.id,t.app.settings);
  assert.equal(acknowledged.financialConsent,false);
  assert.equal(acknowledged.orderCreated,false);
  const before=await t.db.one<any>('select acknowledged_at from planned_reservation_estimates where id=$1',[quote.id]);
  t.clock.advance(10);
  await agreement.acknowledgePlannedEstimate(owner,selected,2,quote.id,t.app.settings);
  assert.deepEqual(await t.db.one<any>('select acknowledged_at from planned_reservation_estimates where id=$1',[quote.id]),before);
  await agreement.select(master,selected,2,night);
  await assert.rejects(agreement.acknowledgePlannedEstimate(owner,selected,3,quote.id,t.app.settings),code('not_found'));
  const newQuote=await agreement.quotePlanned(owner,selected,3,site,t.app.settings);
  assert.equal(newQuote.snapshot.tariff.night,true);
  await assert.rejects(agreement.confirm(owner,selected,3),code('planned_checkout_required'));
  assert.deepEqual(await t.db.one<any>("select (select count(*)::int from orders) as orders,(select count(*)::int from payments) as payments,(select count(*)::int from order_dispatch) as dispatch"),{orders:0,payments:0,dispatch:0});
});
