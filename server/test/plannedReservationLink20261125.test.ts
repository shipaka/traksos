import {before,after,test} from 'node:test';
import assert from 'node:assert/strict';
import {setup,ok,type T} from './helpers.ts';
import {PlannedOrderIntentService} from '../src/services/plannedOrderIntent.ts';
import {ReservationAgreement} from '../src/services/reservationAgreement.ts';
let t:T,intents:PlannedOrderIntentService,agreement:ReservationAgreement;
let owner:{id:string;token:string},driver:typeof owner,master:typeof owner,other:typeof owner,tow:typeof owner;
let vehicle:string,qr:string;
const time={startsAt:'2026-12-03T08:00:00Z',endsAt:'2026-12-03T10:00:00Z'};
const code=(c:string)=>(e:any)=>e?.code===c;
before(async()=>{
  t=await setup();
  owner=await t.login('+79997811101');driver=await t.login('+79997811102');
  master=await t.login('+79997811103','master');other=await t.login('+79997811104','master');
  tow=await t.login('+79997811105','tow');
  for(const u of [master,other])ok(await t.api('PUT','/api/performer/profile',{kind:'master',name:'Мастер',specialties:['electric']},u.token));
  ok(await t.api('PUT','/api/performer/profile',{kind:'tow',name:'Эвакуатор'},tow.token));
  vehicle=ok(await t.api('POST','/api/vehicles',{brand:'DAF',model:'XF',plate:'А123АА178'},owner.token)).id;
  qr=ok(await t.api('GET','/api/fleet',undefined,owner.token)).cars[0].qrCode;
  ok(await t.api('POST',`/api/qr/${qr}/join`,{},driver.token));
  intents=new PlannedOrderIntentService(t.db,t.clock.now);
  agreement=new ReservationAgreement(t.db,t.app.orders,t.clock.now);
});
after(()=>t?.close());
const request=(key:string)=>intents.request(driver,{vehicleId:vehicle,service:'electric',requestKey:key,...time});
test('intent must be approved and matched to actual service; concurrent requests produce only one tentative reservation',async()=>{
  const i=await request('linked_intent_0001');
  await assert.rejects(agreement.requestForIntent(owner,i.id,master.id,'linked_reserve_001'),code('planned_permission_required'));
  await intents.decide(owner,i.id,1,true);
  await assert.rejects(agreement.requestForIntent(driver,i.id,master.id,'linked_reserve_001'),code('forbidden'));
  await assert.rejects(agreement.requestForIntent(owner,i.id,tow.id,'linked_reserve_001'),code('forbidden'));
  const outcomes=await Promise.allSettled([agreement.requestForIntent(owner,i.id,master.id,'linked_reserve_001'),agreement.requestForIntent(owner,i.id,other.id,'linked_reserve_002')]);
  const success=outcomes.filter(x=>x.status==='fulfilled');
  assert.equal(success.length,1);
  const a=(success[0] as PromiseFulfilledResult<any>).value;
  const performer=a.performer_id===master.id?master:other;
  assert.equal(a.status,'proposed');assert.equal(a.planned_intent_id,i.id);
  assert.equal((await agreement.requestForIntent(owner,i.id,performer.id,a.request_key)).id,a.id);
  await assert.rejects(agreement.request(owner,performer.id,time,a.request_key),code('reservation_key_reused'));
  await agreement.select(performer,a.id,1,time);
  await assert.rejects(agreement.confirm(owner,a.id,2),code('planned_checkout_required'));
  await assert.rejects(t.db.query("update performer_time_reservations set status='confirmed',decision_at=$2,decided_by=$3 where id=$1",[a.id,t.clock.now(),owner.id]));
  assert.equal(await t.app.orders.hasUpcomingReservation(t.db,performer.id),false);
  const counts=await t.db.one<any>("select (select count(*)::int from orders) as orders,(select count(*)::int from payments) as payments,(select count(*)::int from order_dispatch) as dispatch");
  assert.deepEqual(counts,{orders:0,payments:0,dispatch:0});
});
test('revoked driver access prevents new negotiation and further time selection, but cancellation stays available',async()=>{
  const i=await request('linked_intent_0002');await intents.decide(owner,i.id,1,true);
  const a=await agreement.requestForIntent(owner,i.id,master.id,'linked_reserve_003');
  const j=await request('linked_intent_0003');await intents.decide(owner,j.id,1,true);
  ok(await t.api('POST',`/api/fleet/vehicles/${vehicle}/new-qr`,{},owner.token));
  await assert.rejects(agreement.requestForIntent(owner,j.id,master.id,'linked_reserve_004'),code('forbidden'));
  await assert.rejects(agreement.select(master,a.id,1,time),code('forbidden'));
  assert.equal((await agreement.cancel(owner,a.id,1,'Водитель больше не закреплён')).status,'cancelled');
});
