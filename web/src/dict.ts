/** Подсказка по машине — показываем в гараже и в заявке, чтобы подобрать мастера с нужным оборудованием */
export function seriesHint(brand?: string | null, year?: number | string | null): string | null {
  const y = Number(year) || null;
  if (!brand) return null;
  if (/scania/i.test(brand) && y && y >= 2007 && y <= 2011) return 'Scania 2007–2011: переходная серия, капризный координатор — не каждая диагностика подходит. Подберём мастера с совместимым оборудованием.';
  if (y && y >= 2014) return 'Евро-6: много электроники и AdBlue — подберём мастера с диагностикой под вашу марку.';
  return null;
}

