// Справка «Как всё устроено»: коротко по разделам, цифры — из настроек площадки, а не из головы.
import { useState } from 'react';
import { rub } from '../api.ts';
import { useMe, Back } from '../ui.tsx';
import { usePrices } from './client.tsx';

type Item = [string, string];

export function Help() {
  const { me, mode } = useMe();
  const { pricing: p } = usePrices();
  const [q, setQ] = useState('');
  const fee = p?.clientFeePct ?? 5;
  const consult = p?.consult ?? { price: 70_000, backDiscount: 20_000, backHours: 48 };
  const sc = p?.cancelScale ?? {};
  const keep = (k: string) => `${Math.round((1 - (sc[k] ?? 0)) * 100)}%`;
  const isDriver = !!me?.owner_id;

  const client: Item[] = [
    ['Суммы до вызова и оферта', `Перед вызовом вы видите выезд, час работы и наценки мастера. Галочка «Согласен» — согласие с офертой, от имени вашей компании, если она указана в профиле. На месте мастер называет сумму за работу, и она уходит вам на подтверждение — без вашего «Подтвердить» сумма не меняется.`],
    ['Как устроена оплата', `Наличными мастеру, онлайн или по счёту для компаний — какие способы включены, видно в форме заявки. Сервисный сбор ТракSOS — ${fee}% и уже входит в показанные суммы. При онлайн-оплате деньги уходят исполнителю после того, как вы подтвердите сумму.`],
    ['Консультация и скидка на выезд', `Консультация по телефону стоит ${rub(consult.price)}: мастер звонит или пишет, подсказывает, что проверить. Если в течение ${consult.backHours} часов понадобится выезд по той же машине — скидка ${rub(consult.backDiscount)} на него, один раз. Консультацию закрывает мастер, вы подтверждаете «Вопрос решён».`],
    ['Кто что видит', 'Исполнитель видит то, что нужно для работы: компанию, машину и историю работ по ней — что и когда делали. Ваши расходы и суммы прошлых заказов не видит никто, кроме вас. Номера телефонов в чате скрываются.'],
    ['Отмена и возврат', `Пока исполнитель не выбран — отмена бесплатно. Принял заявку — вернём ${keep('accepted')} выезда. Едет, первая половина пути — ${keep('en_route_first_half')}, почти на месте — ${keep('en_route_second_half')}. Если подвёл исполнитель — возврат полностью. Сбор ТракSOS возвращается в той же доле.`],
    ['Место и условия', 'В заявке отметьте, где машина: парковка, стоянка, завод или трасса. Для завода — нужен ли пропуск и кто встретит. Если идёт погрузка или другие работы — отметьте: мастер увидит это до выезда.'],
    ['Мои мастера', 'Мастера, у которых вы уже ремонтировались, сохраняются в «Заявках» → «Мои мастера». Избранных предлагаем первыми, отмеченных «Не предлагать» — не предлагаем вовсе.'],
    ['Сервисы-партнёры', `Если на месте не исправить, мастер может посоветовать рембазу-партнёра. Записались через ТракSOS по его совету — скидка ${p?.serviceReferralDiscountPct ?? 5}% в счёте сервиса. Статус ремонта виден в «Заявках», работы сверяете перед оплатой; не согласны — спор с модератором.`],
    ['Отзывы и рейтинг', 'Оценивают друг друга обе стороны. После работы вы ставите звёзды и сверяете перечень работ. Сделано не то или больше, чем согласовали, — откройте спор: модератор посмотрит заявку и чат.'],
    ['Если исполнитель не приехал', 'Отмените заявку с причиной «Мастер не приехал» или позовите поддержку прямо из заявки — модератор разберётся, выезд вернём.'],
    ['Ваши данные', 'Скачать, исправить или удалить свои данные можно в разделе «Персональные данные» в профиле.'],
  ];
  const owner: Item[] = [
    ['Владелец и водители', 'Кабинет — у владельца. Водитель входит по QR-наклейке в кабине: телефон и код из SMS — и сразу работает с этой машиной. Владелец задаёт лимит на заказ и на месяц или подтверждает каждый заказ сам. SOS водителю доступен всегда. Все заказы и чаты водителей видит владелец.'],
    ['Документы', 'Укажите компанию, ИНН и идентификатор ЭДО в «Моём парке» — документы по заказам будут оформляться на компанию.'],
  ];
  const driver: Item[] = [
    ['Что я могу', 'Вызвать помощь по кнопке SOS — всегда, даже если владелец не на связи. Остальное — мастер, эвакуатор, запись в сервис — если владелец это разрешил.'],
    ['Лимит и подтверждение', 'Заказы до лимита идут сразу. Дороже — владелец получает уведомление и подтверждает. Статус виден в заявке.'],
    ['Что я вижу', 'Только машину, на которой работаете, и свои заказы. Другие машины и расходы компании вам не показываются. Новый водитель вошёл по наклейке — доступ прежнего закрывается.'],
  ];
  const performer: Item[] = [
    ['Как приходят заявки', 'Пока вы «Свободен» и в рабочие часы распорядка — заявки приходят звонком или в торги. «На звонке» — только консультации. «Перерыв» и «Не на линии» — не звоним. В конце рабочего дня вас снимает с линии само, до утра или пока не выйдете сами.'],
    ['Кого вам предлагают', 'Клиенту с маркой, которую вы отметили «отлично», вас предложат выше. «Что всегда в машине» и наценки клиент видит в отклике. Клиента, отмеченного «Не брать», вам больше не покажут.'],
    ['Комиссия и деньги', `С заказов через ТракSOS удерживается комиссия ${p?.performerCommissionPct ?? 5}%. Все начисления, списания и выплаты — в «Профиль → Финансы»; по любой операции можно задать вопрос, поддержка увидит её целиком.`],
    ['Опоздания', 'Обещанное время — ваше время на сборы плюс дорога. Задерживаетесь — нажмите «Опаздываю»: клиент сразу увидит новое время.'],
    ['На месте не исправить', 'Посоветуйте сервис-партнёр из заявки — клиенту там скидка.'],
  ];
  const service: Item[] = [
    ['Что нужно заполнять', 'Минимум: ответить на запрос, назначить время, отмечать статус ремонта и нажать «Машина готова» с галочками, что делали. Заметки — по желанию, клиенту показываются, только если вы включили.'],
    ['Карточка сервиса', 'Один раз отметьте, что принимаете, кто у вас есть (есть у нас / приглашаем / нет), условия и марки. Раз в неделю спросим: приём всё так же? Дни без работы — запись на них закрыта.'],
    ['Счёт и комиссия', `После «Выставить счёт» клиент сверяет работы. С работ по клиентам ТракSOS — комиссия ${p?.serviceCommissionPct ?? 10}%. Скидка клиенту по совету мастера оплачивается из комиссии ТракSOS — ваша выручка не меняется.`],
    ['Клиенты по совету мастера', 'Если ремонт долгий, раз в неделю отметьте «ещё у нас» в карточке машины.'],
  ];
  const sections: [string, Item[]][] = mode === 'service' ? [['Рембаза', service]]
    : mode === 'performer' ? [['Исполнителю', performer]]
    : isDriver ? [['Водителю', driver], ['Как всё устроено', client]]
    : [['Как всё устроено', client], ['Владельцу парка', owner]];
  const match = (it: Item) => !q.trim() || (it[0] + ' ' + it[1]).toLowerCase().includes(q.trim().toLowerCase());
  return (
    <main>
      <Back to="" label="Назад" />
      <div><h1>Справка</h1><div className="sub">Коротко о том, как устроены суммы, оплата, отмена и кто что видит.</div></div>
      <input className="field" type="search" placeholder="Поиск по справке" value={q} onChange={(e) => setQ(e.target.value)} />
      {sections.map(([title, items]) => {
        const shown = items.filter(match);
        if (!shown.length) return null;
        return (
          <div key={title} className="stack">
            <span className="label">{title}</span>
            {shown.map(([h, t]) => (
              <details key={h} className="card" open={!!q.trim()}>
                <summary><b>{h}</b></summary>
                <span className="note" style={{ color: 'var(--fg)', lineHeight: 1.5 }}>{t}</span>
              </details>
            ))}
          </div>
        );
      })}
      <a className="btn ghost" href="#/support/new">Не нашли ответ — написать в поддержку</a>
      <a className="note" href="#/offer/client">Оферта для клиентов</a>
      {mode !== 'client' && <a className="note" href="#/offer/performer">Агентский договор</a>}
    </main>
  );
}
