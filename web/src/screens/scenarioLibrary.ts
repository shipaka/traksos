/**
 * TrakSOS situational training: fictional decisions only.
 * No API calls, no orders, no mediation verdicts, no guarantees of payouts.
 * Shared pure data for the role-scoped help encyclopedia and regression tests.
 */
export type CourseRole = 'owner'|'driver'|'master'|'tow'|'service'|'insurer'|'inspection'|'moderator'|'admin';
export type ScenarioChoice = {
  label:string;
  feedback:string;
  recommended:boolean;
};
export type ScenarioStep = {
  situation:string;
  where:string;
  why:string;
  choices:readonly ScenarioChoice[];
};
export type Scenario = {
  id:string;
  title:string;
  category:'Споры и оплата'|'Срыв заявки'|'Безопасность'|'Связь и доступ'|'Документы'|'Модерация';
  difficulty:'Базовый'|'Форс-мажор'|'Критическая ситуация';
  roles:readonly CourseRole[];
  summary:string;
  outcome:string;
  link:string;
  linkLabel:string;
  steps:readonly ScenarioStep[];
};

const ownerDriver:CourseRole[]=['owner','driver'];
const onRoad:CourseRole[]=['master','tow'];
const business:CourseRole[]=['master','tow','service'];
const staff:CourseRole[]=['moderator','admin'];
const everyone:CourseRole[]=['owner','driver','master','tow','service','insurer','inspection','moderator','admin'];

function decision(situation:string,where:string,why:string,
  goodLabel:string,goodFeedback:string,badLabel:string,badFeedback:string,
  otherLabel:string,otherFeedback:string):ScenarioStep {
  return {situation,where,why,choices:[
    {label:goodLabel,feedback:goodFeedback,recommended:true},
    {label:badLabel,feedback:badFeedback,recommended:false},
    {label:otherLabel,feedback:otherFeedback,recommended:false},
  ]};
}

