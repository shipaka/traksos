export function scenariosForRole(role:CourseRole, query=''):Scenario[] {
  const q=query.trim().toLocaleLowerCase('ru');
  return scenarioLibrary.filter(s=>s.roles.includes(role) &&
    (!q || [s.title,s.summary,s.category,s.difficulty,...s.steps.map(x=>x.situation)].join(' ').toLocaleLowerCase('ru').includes(q)));
}
export function allowedScenario(role:CourseRole,id:string):Scenario|null {
  return scenariosForRole(role).find(s=>s.id===id)??null;
}
export function chooseScenarioOption(s:Scenario,stage:number,option:number):{
  valid:boolean;recommended:boolean;nextStage:number;finished:boolean;feedback:string;
} {
  if(!Number.isInteger(stage)||stage<0||stage>=s.steps.length||
     !Number.isInteger(option)||option<0||option>=s.steps[stage].choices.length)
    return {valid:false,recommended:false,nextStage:stage,finished:false,feedback:'Неверный шаг обучения'};
  const item=s.steps[stage].choices[option];
  return {valid:true,recommended:item.recommended,
    nextStage:item.recommended?Math.min(s.steps.length-1,stage+1):stage,
    finished:item.recommended&&stage===s.steps.length-1,
    feedback:item.feedback};
}
